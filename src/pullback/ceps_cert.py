def strict_triangle(sa, sb, sc, tol=None):
    """``sqrt(sa) + sqrt(sb) > sqrt(sc)``, without taking square roots.

    Squaring twice: with ``S = sa + sb - sc``,

        sqrt(sa) + sqrt(sb) > sqrt(sc)
          <=>  sc - sa - sb < 2 sqrt(sa sb)
          <=>  S > 0  or  S^2 < 4 sa sb.

    The ``S == 0`` case is a *strict* triangle (``sa + sb = sc`` still leaves the
    cross term ``2 sqrt(sa sb)`` positive), and getting that case wrong was a
    real defect caught by the rational bipyramid fixture.  A tolerance only
    ever makes the test stricter, so it can never manufacture a pass.
    """
    if not (sa > 0 and sb > 0 and sc > 0):
        return False
    S = sa + sb - sc
    if S > 0:
        return True
    lhs, rhs = 4 * sa * sb, S * S
    return lhs > rhs if tol is None else lhs > rhs * (1 + tol)


def check_metric(cx, sq, tol=None):
    rep = Report("metric", "exact" if tol is None else "numeric")
    missing = [e for e in cx.edges if e not in sq]
    rep.add("edge_lengths_present", not missing,
            "%d edges, %d missing" % (len(cx.edges), len(missing)), missing[:6])
    nonpos = [e for e in cx.edges if e in sq and not sq[e] > 0]
    rep.add("edge_lengths_positive", not nonpos,
            "%d non-positive" % len(nonpos), nonpos[:6])
    broken = []
    for t, f in enumerate(cx.faces):
        a = sq[canon(f[0], f[1])]
        b = sq[canon(f[1], f[2])]
        c = sq[canon(f[2], f[0])]
        if not (strict_triangle(a, b, c, tol)
                and strict_triangle(b, c, a, tol)
                and strict_triangle(c, a, b, tol)):
            broken.append((t, f))
    rep.add("strict_triangle_inequality", not broken,
            "%d of %d faces violate" % (len(broken), len(cx.faces)),
            broken[:6])
    return rep


