# --------------------------------------------------------------------------
# generic 3-vector algebra (Fraction, mpmath.mpf, float, sympy numbers)
# --------------------------------------------------------------------------
def vsub(a, b):
    return (a[0] - b[0], a[1] - b[1], a[2] - b[2])


def vadd(a, b):
    return (a[0] + b[0], a[1] + b[1], a[2] + b[2])


def vscale(s, a):
    return (s * a[0], s * a[1], s * a[2])


def vdot(a, b):
    return a[0] * b[0] + a[1] * b[1] + a[2] * b[2]


def vcross(a, b):
    return (a[1] * b[2] - a[2] * b[1],
            a[2] * b[0] - a[0] * b[2],
            a[0] * b[1] - a[1] * b[0])


def vnorm2(a):
    return vdot(a, a)


def canon(i, j):
    return (i, j) if i <= j else (j, i)


def is_exact(x):
    return Fraction is not None and isinstance(x, Fraction)


def fmt(x):
    try:
        return "%.17g" % float(x)
    except (TypeError, OverflowError):
        return str(x)


# --------------------------------------------------------------------------
# report
# --------------------------------------------------------------------------
class Report:
    """Ordered collection of independent verdicts; each one stands alone."""

    def __init__(self, title="", tier="exact"):
        self.title = title
        self.tier = tier
        self.rows = []

    def add(self, name, ok, detail="", value=None, gauge=False):
        """Record one verdict.

        ``gauge=True`` marks a verdict that depends on which representative of
        the Mobius class the caller chose (the origin being inside the
        polyhedron, the radial degree in that gauge).  Gauge rows are reported
        but are not part of the intrinsic certificate: a Mobius image of a
        correct answer must not be rejected for moving the origin.
        """
        self.rows.append({"check": name, "ok": bool(ok), "detail": detail,
                          "value": value, "gauge": bool(gauge)})
        return bool(ok)

    def __getitem__(self, name):
        for r in self.rows:
            if r["check"] == name:
                return r
        raise KeyError(name)

    def ok(self, *names):
        if not names:
            return all(r["ok"] for r in self.rows if not r["gauge"])
        return all(self[r]["ok"] for r in names)

    def failing(self, include_gauge=False):
        return [r["check"] for r in self.rows
                if not r["ok"] and (include_gauge or not r["gauge"])]

    def gauge_failing(self):
        return [r["check"] for r in self.rows if r["gauge"] and not r["ok"]]

    def summary(self):
        intr = [r for r in self.rows if not r["gauge"]]
        g = [r for r in self.rows if r["gauge"]]
        head = "PASS" if all(r["ok"] for r in intr) else "FAIL"
        tail = ""
        if g:
            tail = ", gauge %d/%d" % (sum(1 for r in g if r["ok"]), len(g))
        return "%s %s [%s] %d/%d%s" % (head, self.title, self.tier,
                                       sum(1 for r in intr if r["ok"]),
                                       len(intr), tail)

    def __str__(self):
        out = [self.summary()]
        for r in self.rows:
            out.append("  %-26s %-4s%s %s"
                       % (r["check"], "ok" if r["ok"] else "FAIL",
                          " [gauge]" if r["gauge"] else "", r["detail"]))
        return "\n".join(out)

    def extend(self, other):
        self.rows.extend(other.rows)
        return self

    def as_dict(self):
        return {"title": self.title, "tier": self.tier, "ok": self.ok(),
                "rows": self.rows}


# --------------------------------------------------------------------------
# the complex
# --------------------------------------------------------------------------
class Complex:
    """A consistently oriented triangulated closed surface.

    ``faces`` is a list of triples; ``faces[t] -> faces[(t+1)%3]`` is the
    positive dart.  Coherent orientation is checked, not assumed.
    """

    def __init__(self, n, faces):
        self.n = int(n)
        self.faces = [tuple(int(x) for x in f) for f in faces]
        self.incident = {}
        self.dart = {}
        self.at = {}
        for t, f in enumerate(self.faces):
            for s in range(3):
                d = (f[s], f[(s + 1) % 3])
                self.dart[d] = t
                self.incident.setdefault(canon(*d), []).append(t)
            for v in f:
                self.at.setdefault(v, []).append(t)
        self.edges = dict(self.incident)

    def problems(self):
        bad, seen = [], set()
        for t, f in enumerate(self.faces):
            if len(set(f)) != 3:
                bad.append(("degenerate face", t, f))
            if not all(0 <= v < self.n for v in f):
                bad.append(("vertex out of range", t, f))
            key = frozenset(f)
            if key in seen:
                bad.append(("repeated face", t, f))
            seen.add(key)
        for e, ts in self.edges.items():
            if len(ts) != 2:
                bad.append(("edge not in two faces", e, len(ts)))
            if self.dart.get(e) == self.dart.get((e[1], e[0])):
                bad.append(("dart and opposite in one face", e))
        for (i, j) in self.dart:
            if (j, i) not in self.dart:
                bad.append(("dart without opposite", (i, j)))
        used = {v for f in self.faces for v in f}
        if used != set(range(self.n)):
            bad.append(("unused vertices", sorted(set(range(self.n)) - used)))
        return bad

    def components(self):
        parent = list(range(max(1, len(self.faces))))

        def root(x):
            while parent[x] != x:
                parent[x] = parent[parent[x]]
                x = parent[x]
            return x

        for ts in self.incident.values():
            if len(ts) == 2:
                a, b = root(ts[0]), root(ts[1])
                if a != b:
                    parent[a] = b
        return len({root(t) for t in range(len(self.faces))})

    def euler(self):
        return self.n - len(self.edges) + len(self.faces)

    def link_order(self, v):
        """Cyclic order of the neighbours of ``v``; ``None`` if not one cycle."""
        if v not in self.at:
            return None
        start = min(self.at[v])
        order, seen, t = [], set(), start
        while True:
            if t in seen:
                return None
            seen.add(t)
            f = self.faces[t]
            s = f.index(v)
            out = f[(s + 1) % 3]
            order.append(out)
            t = self.dart.get((out, v))
            if t is None:
                return None
            if t == start:
                break
        return order if len(seen) == len(self.at[v]) else None

    def third(self, i, j):
        """Third vertex of the face carrying the dart ``i -> j``."""
        f = self.faces[self.dart[(i, j)]]
        return f[(f.index(i) + 2) % 3]

    def flip(self, e):
        """Ptolemy flip of the interior edge ``e``; returns a new Complex.

        The two adjacent faces are replaced by the other diagonal; no
        geometric validity check happens here (``replay_flips`` does that).
        """
        i, j = e
        k, l = self.third(i, j), self.third(j, i)
        drop = {frozenset((i, k, j)), frozenset((i, j, l))}
        faces = [f for f in self.faces if frozenset(f) not in drop]
        faces.append((k, l, j))
        faces.append((i, k, l))
        return Complex(self.n, faces)


def check_complex(cx):
    rep = Report("complex", "exact")
    bad = cx.problems()
    rep.add("well_formed", not bad, "%d problem(s)" % len(bad), bad[:8])
    comps = cx.components()
    rep.add("connected", comps == 1, "%d component(s)" % comps, comps)
    rep.add("euler_2", cx.euler() == 2,
            "V - E + F = %d - %d + %d = %d"
            % (cx.n, len(cx.edges), len(cx.faces), cx.euler()), cx.euler())
    bad_links = [v for v in range(cx.n) if cx.link_order(v) is None]
    rep.add("links_single_cycle", not bad_links,
            "%d vertex link(s) not a single cycle" % len(bad_links),
            bad_links[:8])
    low = [v for v in range(cx.n) if len(cx.at.get(v, ())) < 3]
    rep.add("min_degree", not low, "vertices of face degree < 3: %s" % low)
    return rep


def oriented_same(cx1, cx2):
    """True iff the two complexes have the same darts, i.e. the same orientation."""
    return cx1.dart == cx2.dart


