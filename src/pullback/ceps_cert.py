def angle_at(points, f, v):
    """Angle at ``v`` of the Euclidean triangle spanned by ``points[f]``."""
    s = f.index(v)
    a = points[v]
    u = vsub(points[f[(s + 1) % 3]], a)
    w = vsub(points[f[(s + 2) % 3]], a)
    nu = math.sqrt(float(vnorm2(u)))
    nw = math.sqrt(float(vnorm2(w)))
    if nu * nw == 0:
        return 0.0                          # degenerate face; caught elsewhere
    cosang = float(vdot(u, w)) / (nu * nw)
    cosang = max(-1.0, min(1.0, cosang))
    return math.acos(cosang)


def vertex_angle_sums(points, cx):
    """Sum of the face angles at every vertex, in radians."""
    sums = [0.0] * cx.n
    for f in cx.faces:
        for v in f:
            sums[v] += angle_at(points, f, v)
    return sums


def check_gauss_bonnet(points, cx, tol=1e-9):
    """The total angle defect of a convex inscribed sphere is ``4 pi``.

    ``sum_v (2 pi - Theta_v) = 2 pi chi = 4 pi`` (Gauss--Bonnet).  For a
    *convex inscribed* polyhedron every vertex has ``Theta_v < 2 pi`` (positive
    curvature), so ``Theta_v = 2 pi`` is not a property of the answer -- that is
    the *flat disk* layout condition of GSC §7.5, a different stage.  This row
    is a necessary condition: a configuration with the wrong curvature total
    (a collapse, a fold, a wrong genus) fails it.
    """
    rep = Report("gauss_bonnet", "numeric")
    sums = vertex_angle_sums(points, cx)
    total = sum(2 * math.pi - s for s in sums)
    rep.add("total_angle_defect_4pi", abs(total - 4 * math.pi) <= tol * 4 * math.pi,
            "sum_v (2 pi - Theta_v) = %.15g, 4 pi = %.15g, rel. dev. %.3g"
            % (total, 4 * math.pi, abs(total - 4 * math.pi) / (4 * math.pi)),
            total)
    rep.add("all_vertices_positively_curved",
            all(s < 2 * math.pi + 1e-12 for s in sums),
            "max_v Theta_v = %.15g (must be < 2 pi = %.15g)"
            % (max(sums), 2 * math.pi), max(sums))
    return rep


# --------------------------------------------------------------------------
# cover / label bookkeeping (item 6: never mistake a collapse for a lift)
# --------------------------------------------------------------------------
def check_cover(out, expect):
    """Combinatorial cover certificate, kept apart from the metric ones.

    ``expect = {"d": d, "proj": {lifted: base}, "ld": {lifted: local degree},
    "fibres": {base: [ld, ...]}, "base_faces": [(a,b,c), ...]}``.

    Checks that every lifted vertex projects, the local degrees in each fibre
    sum to ``d`` and match the declared profile, every lifted face projects to
    a base face with three distinct images, and each base face is the image of
    exactly ``d`` lifted faces.  This is where a "degree d collapse" -- a
    configuration that is not a cover at all -- is caught.
    """
    rep = Report("cover", "exact")
    d = int(expect["d"])
    proj, ld = expect["proj"], expect.get("ld")
    fib = {}
    missing = [v for v in range(out.n) if v not in proj]
    for v in range(out.n):
        if v not in proj:
            continue
        fib.setdefault(proj[v], []).append(ld[v] if ld else 1)
    rep.add("every_vertex_projects", not missing,
            "%d lifted vertices without a projection" % len(missing), missing[:6])
    bad = {b: sum(s) for b, s in fib.items() if sum(s) != d}
    rep.add("fibre_degree_total", not bad,
            "fibres with sum(ld) != %d: %s" % (d, bad), bad)
    if ld is not None and "fibres" in expect:
        wrong = {b: (sorted(s), sorted(expect["fibres"].get(b, [])))
                 for b, s in fib.items()
                 if sorted(s) != sorted(expect["fibres"].get(b, []))}
        rep.add("fibre_profile_matches", not wrong,
                "%d fibres differ" % len(wrong), list(wrong)[:6])
    if "base_faces" in expect:
        base = {frozenset(f) for f in expect["base_faces"]}
        per, bad_faces = {}, []
        for f in out.faces:
            img = frozenset(proj[v] for v in f if v in proj)
            if len(img) != 3 or img not in base:
                bad_faces.append(f)
                continue
            per[img] = per.get(img, 0) + 1
        rep.add("faces_project_to_base_faces", not bad_faces,
                "%d bad lifted faces" % len(bad_faces), bad_faces[:6])
        rep.add("d_lifted_faces_per_base",
                all(c == d for c in per.values()) and len(per) == len(base),
                "multiplicities %s over %d of %d base faces"
                % (sorted(set(per.values())), len(per), len(base)))
    parallel = {}
    for e in out.edges:
        parallel.setdefault(e, []).append(e)
    rep.add("parallel_labels", True,
            "%d vertex pairs, labels keyed by pair (no label dropped)"
            % len(parallel))
    return rep


# --------------------------------------------------------------------------
# the driver
# --------------------------------------------------------------------------
def certify(cx, sq_in, points, cx_out=None, u=None, flips=None,
            expect_cover=None, name="", tol=None):
    """Decide whether ``(points, cx_out)`` is a correct CEPS realisation.

    Parameters
    ----------
    cx, sq_in
        the input: an oriented triangulated sphere and the squared edge
        lengths of its PL metric, keyed by ``canon(i, j)``.
    points
        the claimed realisation, one 3-vector per vertex.
    cx_out
        the claimed final complex; ``None`` means the input complex.
    u
        optional vertex scale factors, checked if given.
    flips
        optional flip history from ``cx`` to ``cx_out``, replayed.
    expect_cover
        optional cover expectations (see ``check_cover``).  Kept separate from
        the metric verdicts and never used to infer them.
    tol
        ``None`` for exact arithmetic, otherwise a relative tolerance.

    Acceptance is ``report.ok('supporting', 'on_sphere', 'degree', 'delaunay',
    'cross_ratio', 'scaling')``.  A residual is nowhere in that list.
    """
    tier = "exact" if tol is None else "numeric"
    rep = Report(name or "CEPS certificate", tier)
    rep.extend(check_complex(cx))
    rep.extend(check_metric(cx, sq_in, tol))
    out = cx if cx_out is None else cx_out
    if cx_out is not None and not oriented_same(cx, cx_out):
        rep.extend(check_complex(out))
    if len(points) != out.n:
        rep.add("points_count", False,
                "%d points for %d vertices" % (len(points), out.n))
        return rep
    rep.extend(check_distinct(points))
    rep.extend(check_on_sphere(points, tol))
    rep.extend(check_supporting(points, out, tol))
    rep.extend(check_gauss_bonnet(points, out))
    rep.extend(check_gauge(points, out, tol))
    sq_out = sq_lengths(points)
    rep.extend(check_delaunay(out, sq_out))
    if oriented_same(cx, out):
        rep.extend(check_cross_ratios(out, sq_in, sq_out, tol))
        rep.extend(check_scaling(out, sq_in, sq_out, tol))
    elif flips is not None:
        lens_in = {e: math.sqrt(float(sq_in[e])) for e in cx.edges}
        cx2, lens2, frep = replay_flips(cx, lens_in, flips)
        rep.extend(frep)
        if oriented_same(cx2, out):
            sq2 = {e: lens2[e] * lens2[e] for e in cx2.edges}
            rep.extend(check_cross_ratios(out, sq2, sq_out, tol))
            rep.extend(check_scaling(out, sq2, sq_out, tol))
        else:
            rep.add("replayed_complex_matches", False,
                    "replaying the flip history did not reach the claimed "
                    "complex")
    else:
        rep.add("cross_ratio", False,
                "not attempted: the final complex differs from the input's "
                "and no flip history was supplied, so the input metric is not "
                "known on the final edges")
    if u is not None:
        rep.extend(check_u(out, sq_in, sq_out, u))
    if expect_cover is not None:
        rep.extend(check_cover(out, expect_cover))
    rep.extend(check_mobius(points, out))
    return rep
