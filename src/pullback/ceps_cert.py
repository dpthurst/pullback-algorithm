def ptolemy_length(l_ik, l_jl, l_il, l_jk, l_ij):
    """Length of the flipped diagonal: ``l_kl = (l_ik l_jl + l_il l_jk)/l_ij``."""
    return (l_ik * l_jl + l_il * l_jk) / l_ij


def replay_flips(cx, lengths, flips):
    """Replay a claimed flip history on a flat metric.

    For each flipped edge the two adjacent triangles are unfolded.  The flip
    preserves the metric iff the two angles opposite the edge sum to less than
    pi, i.e. ``cot a + cot a' >= 0``; the new diagonal then has the Ptolemy
    length.  A history that flips a strictly flippable edge is reported as
    invalid -- that is a non-Delaunay flip and it changes the metric.

    Returns ``(complex, lengths, report)``; lengths are scalars for which
    ``sqrt`` is available (float, mpmath.mpf).
    """
    rep = Report("flip_history", "numeric")
    lens = dict(lengths)
    hist = []
    for step, e in enumerate(flips):
        e = canon(*e)
        if len(cx.incident.get(e, ())) != 2:
            rep.add("flip_%d" % step, False,
                    "edge %s is not interior in the current complex" % (e,))
            return cx, lens, rep
        i, j = e
        k, l = cx.third(i, j), cx.third(j, i)
        if canon(k, l) in cx.edges:
            rep.add("flip_%d_valid" % step, False,
                    "the alternative diagonal %s is already an edge, so this "
                    "flip would duplicate an edge; no flip is available and "
                    "the Delaunay condition cannot be repaired here"
                    % (canon(k, l),))
            return cx, lens, rep
        sq = {x: lens[x] * lens[x] for x in cx.edges}
        sign, info = delaunay_edge(cx, sq, e)
        if sign < 0:
            rep.add("flip_%d_valid" % step, False,
                    "edge %s is strictly flippable (cot-sum < 0): the flip "
                    "would not preserve the metric" % (e,), info)
            return cx, lens, rep
        new = ptolemy_length(lens[canon(i, k)], lens[canon(j, l)],
                             lens[canon(i, l)], lens[canon(j, k)],
                             lens[canon(i, j)])
        cx = cx.flip(e)
        lens = {x: lens[x] for x in cx.edges if x in lens}
        lens[canon(k, l)] = new
        hist.append((step, e, (k, l), new))
    rep.add("history_replayed", True,
            "%d flip(s), every one metric preserving" % len(hist), hist)
    return cx, lens, rep


