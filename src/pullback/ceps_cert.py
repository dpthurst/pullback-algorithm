"""Independent certification of sphere-inscribed CEPS solutions.

What this module decides
------------------------
A CEPS solve (Gillespie--Springborn--Crane 2021, "Discrete Conformal
Equivalence of Polyhedral Surfaces", §7, with Springborn 2019,
arXiv:1707.06848) takes

  * a marked topological sphere ``(S0, V)`` with a piecewise Euclidean
    metric given as strictly positive edge lengths ``l`` on a triangulation
    ``T`` (every face obeys the strict triangle inequality), and
  * a choice of "special" vertex ``v_inf``,

and produces a convex polyhedron ``P`` inscribed in the unit sphere, with
vertex set ``V`` and faces ``Ttilde``, whose chordal metric
``l~_ij = |p_i - p_j|`` is discretely conformally equivalent to ``l``.
Discrete conformal equivalence on a fixed triangulation is

    l~_ij = exp((u_i + u_j)/2) l_ij                       (GSC Eq. 3)

and across triangulations it is generated by those scalings together with
Ptolemy (Delaunay) flips.  Springborn's Theorem 10.5 says the realisation
exists and is unique up to projective/Mobius maps of the sphere.

This module does not solve that problem.  Given a claim -- points, faces,
optionally ``u`` and a flip history -- it decides whether the claim is
correct and separates the reasons, so that a near-zero residual can never
stand in for a certificate.

The checks
----------
``complex``      ``Ttilde`` is a consistently oriented triangulated sphere:
                 three distinct vertices per face, no repeated face, every
                 edge in exactly two faces with opposite darts, face graph
                 connected, Euler characteristic 2, every vertex link a
                 single cycle.
``metric``       positive lengths on every edge and the strict triangle
                 inequality in every face: the *input* is a valid PL metric
                 (not a conclusion about the output).
``distinct``     the output points are pairwise distinct.
``on_sphere``    all output points have one common positive squared norm.
``supporting``   every face spans a plane with all other vertices strictly on
                 one side, and every face normal points away from the origin.
                 With ``on_sphere`` this says: ``P`` is a convex polyhedron
                 inscribed in a sphere, with vertex set exactly ``V`` (no
                 vertex is swallowed by a face or an edge), and the origin is
                 strictly inside.
``degree``       the radial projection ``P -> S^2`` has degree ``+1``, counted
                 exactly by ray casting in a generic rational direction.  A
                 collapsed configuration cannot pass.
``delaunay``     the output triangulation is intrinsically Delaunay for the
                 output chordal metric: on every interior edge
                 ``cot(alpha) + cot(alpha') >= 0``, decided from squared
                 lengths only (GSC Eq. 9/10, Springborn Thm 4.7).
``cross_ratio``  on the *same* oriented complex, every length cross ratio
                 ``c_ij = l_il l_jk / (l_lj l_ki)`` (GSC Eq. 4) agrees between
                 the input metric and the output chordal metric.  ``c`` is
                 invariant under vertex scaling, so this is discrete conformal
                 equivalence with the vertex factors eliminated; GSC §3.2.2:
                 "these metrics are conformally equivalent if and only if they
                 induce the same length cross ratios".
``scaling``      the vertex factors themselves: with ``r_ij = l~^2_ij/l^2_ij``
                 the equations ``k_i k_j = r_ij`` are solved on a spanning tree
                 and then checked on *every* edge.  This is global discrete
                 scaling consistency; a metric that is only locally a vertex
                 scaling passes the tree solve and fails here.
``parallel``     parallel-edge bookkeeping.  Several distinct edge *labels* can
                 stand for one unordered vertex pair (in a branched cover, when
                 two sheets merge at both ends).  Lengths are keyed by vertex
                 pair, the groups are reported, and no label is dropped or
                 double counted.
``mobius``       an explicit gauge: three non-collinear output vertices are sent
                 to three chosen targets in a stereographic chart and the
                 residual on every vertex is reported.  This is the only place
                 where a gauge is pinned, and it is reported as a gauge.

Two tiers
---------
The code is generic in the scalar type.  With ``fractions.Fraction``
coordinates and lengths, every comparison except logarithms is an exact
rational computation and a pass is a proof (``tier='exact'``).  With
``mpmath.mpf`` at high precision the same code decides the same inequalities
to working precision and every reported sign carries a margin
(``tier='numeric'``).  A float64 run says so.

What is deliberately not claimed
--------------------------------
* A small residual of any fixed-triangulation residual (angle sums, Newton
  step, ...) is not a certificate.  ``fixed_triangulation_residual`` computes
  exactly such a residual, and the test battery exhibits a configuration with
  zero interior angle defect that this module rejects because its
  triangulation is not Delaunay for its own chordal metric.
* ``cross_ratio``/``scaling`` on a complex different from the input's need the
  Ptolemy transport of the input metric.  When the caller supplies a flip
  history it is replayed (``replay_flips``); when it does not, the certificate
  refuses to claim those checks and says why -- it does not guess.
* Uniqueness up to Mobius (Springborn Thm 10.5) is only used to read the
  certificate: every check except ``mobius`` is Mobius invariant (the vertex
  factors are free), so any Mobius image of a correct answer also passes.

References
----------
GSC = refs/gillespie-springborn-crane-ceps.txt, §3.2.2 (Eq. 3, 4), §3.5,
§7.1--7.4.  SPR = refs/springborn-1707.06848.txt, Def. 5.14, Prop. 5.16,
Def. 6.1, Props. 6.2--6.3, Prop. 7.17, Thm. 10.5.
"""

