def sq_lengths(points):
    out = {}
    n = len(points)
    for i in range(n):
        for j in range(i + 1, n):
            out[(i, j)] = vnorm2(vsub(points[j], points[i]))
    return out


def check_distinct(points):
    rep = Report("distinct", "exact")
    dups = [(i, j) for i in range(len(points)) for j in range(i + 1, len(points))
            if vnorm2(vsub(points[j], points[i])) == 0]
    rep.add("distinct", not dups, "%d coincident pair(s) of %d points"
            % (len(dups), len(points)), dups[:6])
    return rep


def check_on_sphere(points, tol=None):
    rep = Report("on_sphere", "exact" if tol is None else "numeric")
    norms = [vnorm2(p) for p in points]
    if not norms:
        rep.add("on_sphere", False, "no points")
        return rep
    lo, hi = min(norms), max(norms)
    if tol is None:
        ok = lo > 0 and lo == hi
    else:
        ok = lo > 0 and hi - lo <= tol * hi
    rep.add("on_sphere", ok, "|p|^2 in [%s, %s]" % (fmt(lo), fmt(hi)),
            (lo, hi))
    return rep


def check_supporting(points, cx, tol=None):
    """Every face is a supporting plane *in the orientation the complex gives*.

    For the face ``(a,b,c)`` as it is written in the complex, put
    ``n = (b-a) x (c-a)``.  The condition is that every vertex not on the face
    satisfies ``n . (p_d - a) < 0``.  Then ``n`` is the outward normal, every
    face is a facet of the convex hull, and the complex is the boundary of a
    convex polyhedron with vertex set exactly the given points: no vertex is
    swallowed by a face plane, and a vertex cannot sit on the "wrong" side.

    This form is *orientation sensitive and Mobius invariant*.  Flipping the
    whole complex makes every ``n . (p_d - a) > 0`` and is reported as an
    inverted orientation, which is a real defect of a claimed conformal map.
    Whether the origin happens to be inside is a separate, gauge-dependent
    question (see ``check_gauge``): a projective map of the sphere keeps the
    polyhedron convex but can move the origin out, so it must not affect the
    intrinsic verdict.
    """
    rep = Report("supporting", "exact" if tol is None else "numeric")
    offender = None
    coplanar = []
    inverted = []
    margins = []
    for t, f in enumerate(cx.faces):
        a, b, c = (points[i] for i in f)
        nrm = vcross(vsub(b, a), vsub(c, a))
        nn = vdot(nrm, nrm)
        if nn == 0:
            coplanar.append((t, f, "degenerate face"))
            continue
        neg, pos, worst, broke = 0, 0, None, False
        for d in range(cx.n):
            if d in f:
                continue
            sv = vdot(nrm, vsub(points[d], a))
            if (sv == 0) if tol is None else (abs(sv) <= tol * nn):
                coplanar.append((t, f, d))
                broke = True
                break
            if sv < 0:
                neg += 1
            else:
                pos += 1
            mag = abs(sv) / nn
            if worst is None or mag < worst:
                worst = mag
        if broke:
            continue
        if pos and neg:
            offender = offender or (t, f, "vertices on both sides")
        elif pos and not neg:
            inverted.append((t, f))
        if worst is not None:
            margins.append(worst)
    rep.add("faces_are_supporting",
            offender is None and not coplanar and not inverted,
            "%d coplanar incidence(s), %d face(s) with the outward normal "
            "reversed, first offender %s"
            % (len(coplanar), len(inverted), offender), (offender, coplanar[:6]))
    if margins:
        rep.add("supporting_margin", min(margins) > 0,
                "min normalised vertex-to-face-plane distance = %s"
                % fmt(min(margins)), min(margins))
    return rep


def check_gauge(points, cx, tol=None):
    """Gauge-dependent rows: the origin strictly inside and the radial degree.

    Choosing the representative of the Mobius class whose polyhedron contains
    the origin is an explicit gauge (GSC §7.5 re-inserts ``v_inf`` at the
    centre of stereographic projection, which presupposes exactly this).  The
    rows below are therefore reported as ``gauge``: they say which
    representative is in hand, not whether the answer is right.
    """
    rep = Report("gauge", "exact" if tol is None else "numeric")
    outs, worst = 0, None
    for t, f in enumerate(cx.faces):
        a, b, c = (points[i] for i in f)
        nrm = vcross(vsub(b, a), vsub(c, a))
        nn = vdot(nrm, nrm)
        if nn == 0:
            outs += 1
            continue
        sv = vdot(nrm, points) if False else vdot(nrm, a)
        if sv <= 0:
            outs += 1
        mag = sv / nn
        if worst is None or mag < worst:
            worst = mag
    rep.add("origin_strictly_inside", outs == 0,
            "%d face(s) do not separate the origin from the polyhedron"
            % outs, (outs, worst), gauge=True)
    deg = ray_degree(points, cx, tol=tol)
    for r in deg.rows:
        rep.add("radial_degree", r["ok"], r["detail"], r["value"], gauge=True)
    return rep


def ray_degree(points, cx, directions=None, tol=None):
    """Degree of the radial map, by exact signed ray casting.

    A ray from the origin in a direction meeting no edge or vertex leaves the
    polyhedron through a face with ``n . r > 0`` (+1) and enters through one
    with ``n . r < 0`` (-1); the algebraic count is the degree.
    """
    rep = Report("degree", "exact" if tol is None else "numeric")
    if directions is None:
        directions = [(1, 2, 3), (3, 1, 2), (2, 3, 5), (5, 2, 3), (1, 1, 0),
                      (0, 1, 1), (1, 0, 1), (7, 3, 2), (1, 2, 5), (4, 9, 1)]
    for r in directions:
        count, degenerate = 0, False
        for f in cx.faces:
            a, b, c = (points[i] for i in f)
            nrm = vcross(vsub(b, a), vsub(c, a))
            nr, h = vdot(nrm, r), vdot(nrm, a)
            if nr == 0 or h == 0:
                degenerate = True
                break
            if float(h) / float(nr) <= 0:
                continue
            q = vscale(h / nr, r)
            s1 = vdot(vcross(vsub(b, a), vsub(q, a)), nrm)
            s2 = vdot(vcross(vsub(c, b), vsub(q, b)), nrm)
            s3 = vdot(vcross(vsub(a, c), vsub(q, c)), nrm)
            if s1 == 0 or s2 == 0 or s3 == 0:
                degenerate = True
                break
            if (s1 > 0) == (s2 > 0) == (s3 > 0):
                count += 1 if nr > 0 else -1
        if not degenerate:
            rep.add("degree", count == 1,
                    "radial degree %d in direction %s" % (count, r), count)
            return rep
    rep.add("degree", False, "every trial ray met an edge or a vertex")
    return rep


# --------------------------------------------------------------------------
# intrinsic Delaunay from squared lengths
# --------------------------------------------------------------------------
def cot_opposite_num(sa, sb, sc):
    """Numerator of ``cot`` of the angle opposite the side of squared length
    ``sc``: ``cot C = (sa + sb - sc) / (4 A)``."""
    return sa + sb - sc


def sixteen_area2(sa, sb, sc):
    """``(4A)^2 = 2(sa sb + sb sc + sc sa) - sa^2 - sb^2 - sc^2``."""
    return 2 * (sa * sb + sb * sc + sc * sa) - sa * sa - sb * sb - sc * sc


def delaunay_edge(cx, sq, e):
    """Exact verdict on one interior edge ``e``.

    Returns ``(sign, info)`` with ``sign = sign(cot a + cot a')`` for the two
    angles opposite ``e``: ``> 0`` strictly Delaunay, ``< 0`` strictly
    flippable, ``0`` concyclic (a tie).

    No division by an area is needed.  With numerators ``n1, n2`` and
    ``K = (4A)^2`` the sign of ``n1/A1 + n2/A2`` is the sign of
    ``n1 sqrt(K2) + n2 sqrt(K1)``: equal signs are immediate, opposite signs
    reduce to comparing ``n1^2 K2`` with ``n2^2 K1``.  The test therefore stays
    inside the scalar type of ``sq`` -- rational for rational squared lengths.
    """
    i, j = e
    k, l = cx.third(i, j), cx.third(j, i)
    sa, sb = sq[canon(j, k)], sq[canon(k, i)]
    sc = sq[canon(i, j)]
    n1 = cot_opposite_num(sa, sb, sc)
    K1 = sixteen_area2(sa, sb, sc)
    sa2, sb2 = sq[canon(j, l)], sq[canon(l, i)]
    n2 = cot_opposite_num(sa2, sb2, sc)
    K2 = sixteen_area2(sa2, sb2, sc)
    info = {"edge": (i, j), "opposite": (k, l), "n1": n1, "n2": n2,
            "K1": K1, "K2": K2}
    if K1 <= 0 or K2 <= 0:
        info["degenerate"] = True
        return 0, info
    if n1 == 0 and n2 == 0:
        return 0, info
    if (n1 >= 0) == (n2 >= 0):
        # same sign: the common sign, and n1 = 0 is *not* negative.  Using
        # ``1 if n1 > 0 else -1`` here is wrong when n1 == 0 < n2 and made a
        # Delaunay edge look flippable (caught by the rational bipyramid).
        return (1 if (n1 > 0 or n2 > 0) else -1), info
    lhs, rhs = n1 * n1 * K2, n2 * n2 * K1
    if lhs == rhs:
        return 0, info
    bigger = 1 if lhs > rhs else -1
    return (1 if n1 > 0 else -1) * bigger, info


def delaunay_margin(info):
    """Scale-free size of the cot-sum (negative means flippable)."""
    n1, n2 = float(info["n1"]), float(info["n2"])
    K1, K2 = float(info["K1"]), float(info["K2"])
    if K1 <= 0 or K2 <= 0:
        return -1.0
    x, y = n1 / math.sqrt(K1), n2 / math.sqrt(K2)
    den = max(abs(x), abs(y), 1e-300)
    return (x + y) / den


def check_delaunay(cx, sq):
    """Intrinsic Delaunay condition, edge by edge.

    An edge is *flippable* when its two adjacent triangles form a convex flat
    quadrilateral, and the Delaunay condition is ``cot a + cot a' >= 0``.  Two
    cases are excluded from the test rather than reported as failures:

    * the alternative diagonal already exists as an edge of the complex.  This
      happens exactly for four vertices whose 1-skeleton is complete, e.g. a
      tetrahedron: the flip would duplicate an edge, so no flip is available
      and the triangulation is the intrinsic Delaunay one by default.  A convex
      inscribed tetrahedron *can* have ``cot a + cot a' < 0`` on such an edge;
      that is not a violation, and treating it as one was a defect of an
      earlier version of this module;
    * the two triangles are coplanar-degenerate (zero area), reported through
      the metric and supporting checks.

    So this row is a diagnostic on the *triangulation choice* the caller
    claims, not the core of the certificate: convexity plus discrete conformal
    equivalence already determines the answer up to Mobius (SPR Thm 10.5).
    """
    rep = Report("delaunay", "exact")
    flippable, margins, unflippable = [], [], []
    interior = [e for e in sorted(cx.edges) if len(cx.incident[e]) == 2]
    for e in interior:
        i, j = e
        if (i, j) not in cx.dart or (j, i) not in cx.dart:
            flippable.append((e, "dart missing: malformed complex"))
            continue
        k, l = cx.third(i, j), cx.third(j, i)
        if canon(k, l) in cx.edges:
            unflippable.append((e, (k, l)))
            continue
        sign, info = delaunay_edge(cx, sq, e)
        if info.get("degenerate"):
            flippable.append((e, "degenerate area"))
            continue
        if sign < 0:
            flippable.append((e, (info["n1"], info["n2"])))
        margins.append(delaunay_margin(info))
    rep.add("no_flippable_edge", not flippable,
            "%d flippable of %d interior edges"
            % (len(flippable), len(interior)), flippable[:8])
    rep.add("unflippable_diagonal_present", True,
            "%d edge(s) whose alternative diagonal is already an edge"
            % len(unflippable), unflippable[:6])
    if margins:
        rep.add("delaunay_margin", min(margins) >= 0,
                "min cot-sum margin = %s" % fmt(min(margins)), min(margins))
    return rep


