def cross_ratio_sq(cx, sq, e):
    """Squared length cross ratio of ``e`` (GSC Eq. 4).

    With ``k`` the third vertex of the face carrying ``i -> j`` and ``l`` that
    of the face carrying ``j -> i``::

        c_ij = l_il l_jk / (l_lj l_ki),
        c_ij^2 = sq_il sq_jk / (sq_lj sq_ki)

    ``c`` is invariant under ``l -> exp((u_i+u_j)/2) l``.  The oriented
    convention matters (the other choice inverts ``c``), so it must be used
    consistently for the two metrics -- which it is here.
    """
    i, j = e
    k, l = cx.third(i, j), cx.third(j, i)
    num = sq[canon(i, l)] * sq[canon(j, k)]
    den = sq[canon(l, j)] * sq[canon(k, i)]
    if den == 0:
        return None                      # degenerate: a zero length
    return num / den


def cross_ratios(cx, sq):
    return {e: cross_ratio_sq(cx, sq, e) for e in cx.edges}


def _reldev(x, y):
    """Relative deviation of ``y`` from ``x``, in the scalar type of the input."""
    if x == y:
        return 0
    return abs(y / x - 1)


def _fmt_dev(d):
    """Print a deviation that may be far below float64 range."""
    f = float(d)
    if f != 0.0 or d == 0:
        return "%.3g" % f
    return str(d)


def check_cross_ratios(cx, sq_in, sq_out, tol=None):
    """Equal length cross ratios on every edge.

    ``tol`` is a *relative* tolerance; ``None`` means exact equality, which is
    what the rational tier uses.  A tolerance only ever relaxes a comparison
    that is already meaningful: the quantity is a ratio of products of edge
    lengths, so it carries no scale.
    """
    rep = Report("cross_ratio", "exact" if tol is None else "numeric")
    bad, worst, worst_e = [], 0, None
    for e in sorted(cx.edges):
        c1, c2 = cross_ratio_sq(cx, sq_in, e), cross_ratio_sq(cx, sq_out, e)
        if c1 is None or c2 is None:
            bad.append((e, "zero length: no cross ratio"))
            continue
        d = _reldev(c1, c2)
        if worst_e is None or d > worst:
            worst_e, worst = e, d
        if d == 0:
            continue
        if tol is not None and float(d) <= tol:
            continue
        bad.append((e, d))
    rep.add("same_cross_ratios", not bad,
            "%d of %d edges differ beyond %s; worst relative deviation %s at %s"
            % (len(bad), len(cx.edges),
               "exact equality" if tol is None else "%.1e" % tol,
               _fmt_dev(worst), worst_e),
            (len(bad), worst))
    return rep


def _to_mpf(x):
    """Exact rational (or float) to ``mpf`` without losing a digit."""
    import mpmath as mp
    if is_exact(x):
        return mp.mpf(x.numerator) / mp.mpf(x.denominator)
    return mp.mpf(x)


class NoExactRoot(ArithmeticError):
    """The scaling factor is not rational, so the exact tier is unavailable."""


def _exact_sqrt(x):
    """``sqrt(x)`` as a :class:`Fraction`, or ``None`` if it is irrational."""
    if not is_exact(x):
        return None
    if x < 0:
        return None
    n, d = x.numerator, x.denominator
    rn, rd = math.isqrt(n), math.isqrt(d)
    if rn * rn == n and rd * rd == d:
        return Fraction(rn, rd)
    return None


def _scalar_sqrt(x):
    """``sqrt`` in the scalar type, or raise :class:`NoExactRoot`."""
    if is_exact(x):
        r = _exact_sqrt(x)
        if r is None:
            raise NoExactRoot(x)
        return r
    if hasattr(x, "sqrt"):                       # mpmath.mpf
        return x ** 0.5 if not hasattr(x, "context") else x.sqrt()
    return math.sqrt(x)


def scaling_from_ratios(cx, ratios, root=0):
    """Solve ``k_i k_j = r_ij`` **exactly**, then check every edge.

    The system determines ``k`` completely -- there is *no* free constant: a
    common factor ``c`` would multiply every product by ``c^2``, so it is a
    symmetry of the energy, not of the metric (this is why ``u -> u + h``
    shifts ``E`` by a constant and changes every length).  Fixing ``k_root = 1``
    and propagating multiplicatively along a spanning tree therefore does *not*
    solve the system; it produces a solution of the tree equations only, and
    the later edges look violated even when a solution exists.  That mistake
    was caught by the degree-2 branched-cover fixture.

    The correct closed form uses one triangle at the root.  With a triangle
    ``(i,j,m)``, ``k_i k_j = r_ij``, ``k_i k_m = r_im`` and ``k_j k_m = r_jm``
    give ``k_i^2 = r_ij r_im / r_jm``, so ``k_i`` is determined up to sign, and
    propagation along any spanning tree then determines every other ``k``.  The
    check ``k_i k_j == r_ij`` on *every* edge is the global discrete-scaling
    consistency condition: a metric that is only locally a vertex scaling
    passes the tree propagation and fails here.

    Returns ``(k, violations)``.  Raises :class:`NoExactRoot` when the root is
    irrational and the input was rational (the caller then retries at working
    precision and says so).
    """
    f = cx.faces[cx.at[root][0]]
    i = root
    j, m = [v for v in f if v != i]
    q0 = ratios[canon(i, j)] * ratios[canon(i, m)] / ratios[canon(j, m)]
    k = {root: _scalar_sqrt(q0)}
    adjacency = {}
    for (a, b) in ratios:
        adjacency.setdefault(a, []).append(b)
        adjacency.setdefault(b, []).append(a)
    queue = [root]
    while queue:
        a = queue.pop(0)
        for b in sorted(adjacency.get(a, ())):
            if b not in k:
                k[b] = ratios[canon(a, b)] / k[a]
                queue.append(b)
    if len(k) != cx.n:
        # the ratios do not even connect the vertices: nothing to solve
        return k, [("unreachable vertices", sorted(set(range(cx.n)) - set(k)))]
    violations = []
    for (a, b), r in sorted(ratios.items()):
        if k[a] * k[b] != r:
            violations.append((canon(a, b), r, k[a] * k[b]))
    return k, violations


def check_scaling(cx, sq_in, sq_out, tol=None):
    """Global discrete-scaling consistency ``l~^2_ij = k_i k_j l^2_ij``.

    The factors are solved in closed form (see :func:`scaling_from_ratios`) and
    the relation is checked on every edge, so a metric that is only *locally* a
    vertex scaling fails here.  When the closed-form root is irrational and the
    input was rational, the check is redone at 50 significant digits and the
    report says so instead of pretending to be a proof.
    """
    zero = [e for e in cx.edges if sq_in[e] == 0 or sq_out[e] == 0]
    if zero:
        rep = Report("scaling", "exact")
        rep.add("global_vertex_scaling", False,
                "%d edges have a zero length, so no vertex scaling exists"
                % len(zero), zero[:6])
        return rep
    ratios = {e: sq_out[e] / sq_in[e] for e in cx.edges}
    tier = "exact" if tol is None else "numeric"
    try:
        k, bad = scaling_from_ratios(cx, ratios)
    except NoExactRoot:
        import mpmath as mp
        mp.mp.dps = 50
        ratios = {e: _to_mpf(r) for e, r in ratios.items()}
        k, bad = scaling_from_ratios(cx, ratios)
        tier = "numeric (closed-form factor irrational)"
        tol = tol if tol is not None else 1e-40
    rep = Report("scaling", tier)
    hard = []
    for item in bad:
        if len(item) == 3 and isinstance(item[0], tuple):
            dev = _reldev(item[1], item[2])
            if tol is not None and float(dev) <= tol:
                continue
            hard.append((item[0], _fmt_dev(dev)))
        else:
            hard.append(item)
    rep.add("global_vertex_scaling", not hard,
            "%d of %d edges violate k_i k_j = l~^2/l^2"
            % (len(hard), len(ratios)), hard[:6])
    if not hard:
        vals = sorted(float(v) for v in k.values())
        rep.add("scale_factors_positive", vals[0] > 0,
                "k = exp(u) in [%s, %s]" % (fmt(vals[0]), fmt(vals[-1])),
                (vals[0], vals[-1]))
    return rep


def check_u(cx, sq_in, sq_out, u):
    """If the caller supplies ``u``, check the exponent form directly."""
    rep = Report("u_supplied", "numeric")
    k = {v: math.exp(float(u[v])) for v in range(cx.n)}
    worst, worst_e = 0.0, None
    for e in sorted(cx.edges):
        i, j = e
        want = k[i] * k[j] * float(sq_in[e])
        got = float(sq_out[e])
        rel = abs(got / want - 1.0)
        if worst_e is None or rel > worst:
            worst_e, worst = e, rel
    rep.add("l~^2 = exp(u_i+u_j) l^2", worst < 1e-12,
            "worst relative deviation %.3g at %s" % (worst, worst_e),
            (worst, worst_e))
    return rep


