THETA = load_session(ROOT / "sessions" / "theta.json")
RABBIT = load_session(ROOT / "sessions" / "rabbit.json")
BARYCENTRIC = load_session(ROOT / "sessions" / "barycentric.json")
TETRAHEDRAL = load_session(ROOT / "sessions" / "tetrahedral.json")


def level_group(aut, n):
    gens = []
    for g, perm in aut.level_generators(n).items():
        gens.append(Permutation([perm[i] for i in range(len(perm))]))
    return PermutationGroup(gens)


def orbit_count(aut, n):
    """Number of orbits of the group generated by the level-n
    permutations on X^n.  Cheap (union-find, no sympy) and invariant
    under relabelling of X^n, so it is a conjugacy invariant of the
    automaton's action."""
    from itertools import product
    d = len(aut.sheets)
    verts = list(product(range(d), repeat=n))
    pos = {w: i for i, w in enumerate(verts)}
    parent = list(range(len(verts)))

    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    def union(a, b):
        ra, rb = find(a), find(b)
        if ra != rb:
            parent[rb] = ra

    for w in verts:
        for g in aut.letters:
            img = tuple(aut.state_action(g, list(w)))
            union(pos[w], pos[img])
    return len({find(i) for i in range(len(verts))})


class TestNormalForm(unittest.TestCase):
    def test_theta_matches_fig3d(self):
        base, cover, phi = THETA
        aut = normal_form(base, cover, phi, tree={"q"})
        self.assertEqual(aut.letters, ("p", "r"))
        # in R1 both generator edges cross between the vertex classes:
        # Fig. 3d's a and b both swap the letters
        self.assertEqual(aut.sigma["p"], [1, 0])
        self.assertEqual(aut.sigma["r"], [1, 0])
        # Fig. 3d: a = sigma(b, A), b = (1, 1) with a=p, b=r, up to the
        # sheet swap (our sheet 0 carries A, sheet 1 carries r)
        self.assertEqual(aut.sections["p"], [((0, -1),), ((1, 1),)])
        self.assertEqual(aut.sections["r"], [(), ()])

    def test_tree_independence_on_admissible_trees(self):
        """Two admissible spanning trees of the same session must give the
        same automaton up to relabelling, so the level-n group orders and
        the orbit counts on X^n agree.

        Only *admissible* trees: see test_inadmissible_tree_refused.  An
        earlier version of this test compared theta's {p} and {q} at
        levels 2-4, where the orders happen to agree; they part at level
        7 (see test_theta_deep_orders) and {p} is not admissible at all.
        """
        for name, session in (("barycentric", BARYCENTRIC),
                              ("tetrahedral", TETRAHEDRAL)):
            base, cover, phi = session
            trees = admissible_trees(base, cover, phi)
            self.assertGreaterEqual(len(trees), 2, f"{name}: fewer than 2 trees")
            auts = [normal_form(base, cover, phi, tree=t) for t in trees]
            for n in (2, 3):
                ref = level_group(auts[0], n)
                ref_orbits = orbit_count(auts[0], n)
                for aut, t in zip(auts[1:], trees[1:]):
                    self.assertEqual(level_group(aut, n).order(), ref.order(),
                                     f"{name} {sorted(t)}: level {n} order")
                    self.assertEqual(orbit_count(aut, n), ref_orbits,
                                     f"{name} {sorted(t)}: level {n} orbits")

    def test_theta_admissible_tree_is_the_published_one(self):
        """theta has exactly one admissible tree, {q}; it is the paper's
        tree c, and it is what the default now picks."""
        base, cover, phi = THETA
        self.assertEqual(admissible_trees(base, cover, phi), [frozenset({"q"})])
        default = normal_form(base, cover, phi)
        explicit = normal_form(base, cover, phi, tree={"q"})
        self.assertEqual(default.sigma, explicit.sigma)
        self.assertEqual(default.sections, explicit.sections)

    def test_inadmissible_tree_refused(self):
        """An inadmissible tree has no virtual endomorphism of a rose
        behind it, so it must be refused rather than silently computed."""
        base, cover, phi = THETA
        self.assertFalse(is_admissible_tree(base, cover, phi, {"p"}))
        with self.assertRaises(ValueError) as ctx:
            normal_form(base, cover, phi, tree={"p"})
        self.assertIn("not admissible", str(ctx.exception))
        # ... and can still be inspected on request
        forced = normal_form(base, cover, phi, tree={"p"},
                             require_admissible=False)
        self.assertEqual(forced.letters, ("q", "r"))

    def test_theta_deep_orders(self):
        """The published automaton, at depth: 2, 2^2, 2^3, 2^5, 2^8, 2^14,
        2^25.  This is the check that tells the good presentation from a
        bad spanning tree: tree {p} gives 2^26 at level 7 and 2^4 from
        the other reading of the section.  Level 7 is cheap here
        (128 points); levels 1-4 alone are not discriminating."""
        base, cover, phi = THETA
        aut = normal_form(base, cover, phi)
        orders = [level_group(aut, n).order() for n in range(1, 8)]
        self.assertEqual(orders, [2, 4, 8, 32, 256, 16384, 2 ** 25])

    def test_rabbit_normal_form_equals_rose(self):
        base, cover, phi = RABBIT
        aut = normal_form(base, cover, phi)
        rose = RoseAutomaton(base, cover, phi)
        self.assertEqual(aut.letters, rose.letters)
        self.assertEqual(aut.sigma, rose.sigma)
        self.assertEqual(aut.sections, rose.sections)


class TestGroupOperations(unittest.TestCase):
    def test_inverse_round_trip(self):
        for name, sess in (("theta", THETA), ("rabbit", RABBIT)):
            with self.subTest(session=name):
                base, cover, phi = sess
                aut = normal_form(base, cover, phi)
                for g in aut.letters:
                    w = ((aut.index[g], F),)
                    wi = aut.inverse_word(w)
                    for n in (1, 2, 3):
                        self.assertTrue(aut.is_identity_on_level(w + wi, n),
                                        f"{name}: {g} * {g}^-1 at level {n}")

    def test_section_identity(self):
        """(g h)|_x = g|_{h(x)} . h|_x for all generators and letters."""
        for name, sess in (("theta", THETA), ("rabbit", RABBIT)):
            with self.subTest(session=name):
                base, cover, phi = sess
                aut = normal_form(base, cover, phi)
                for g in aut.letters:
                    for h in aut.letters:
                        word = ((aut.index[g], F), (aut.index[h], F))
                        for x in range(len(aut.sheets)):
                            hx = aut.apply(((aut.index[h], F),), [x])[0]
                            expect = aut.section(((aut.index[g], F),), hx) + \
                                aut.section(((aut.index[h], F),), x)
                            self._assert_words_equal(aut, aut.section(word, x), expect)

    def _assert_words_equal(self, aut, w1, w2, n=3):
        d = len(aut.sheets)
        from itertools import product
        for lw in product(range(d), repeat=n):
            self.assertEqual(aut.apply(w1, list(lw)), aut.apply(w2, list(lw)),
                             f"{w1} vs {w2} at {lw}")

    def test_nucleus_finite(self):
        """Both examples are contracting: the closure of the generators
        under sections is finite.

        History (2026-10-24): with theta's tree {p} the word closure did
        not terminate within cap=20000, and that was recorded as an open
        observation with the suspicion that Automaton.nucleus deduped on
        raw words.  It does dedupe on raw words, but that was not the
        cause: deduping on the action on level 5 instead still gives 5105
        classes by depth 40, still growing.  The cause was the spanning
        tree: {p} is not admissible (is_admissible_tree), so there was no
        automaton to close in the first place.  See test_inadmissible_tree_refused.
        """
        for name, sess in (("theta", THETA), ("rabbit", RABBIT)):
            with self.subTest(session=name):
                base, cover, phi = sess
                aut = normal_form(base, cover, phi)
                elements, closed = aut.nucleus()
                self.assertTrue(closed, f"{name}: nucleus not closed within cap")
                self.assertGreater(len(elements), 1)
                print(f"  {name}: nucleus has {len(elements)} elements")


